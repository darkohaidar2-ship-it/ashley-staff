/**
 * Universal converter for Kurdish/Arabic-Indic (٠-٩) and Persian (۰-۹) digits to standard Western ASCII (0-9).
 * Prevents mobile login rejections when employees type on Kurdish or Arabic virtual keyboards.
 */
export function normalizeKurdishDigits(str: string): string {
  if (!str) return '';
  return str
    .replace(/[\u0660\u06F0]/g, '0')
    .replace(/[\u0661\u06F1]/g, '1')
    .replace(/[\u0662\u06F2]/g, '2')
    .replace(/[\u0663\u06F3]/g, '3')
    .replace(/[\u0664\u06F4]/g, '4')
    .replace(/[\u0665\u06F5]/g, '5')
    .replace(/[\u0666\u06F6]/g, '6')
    .replace(/[\u0667\u06F7]/g, '7')
    .replace(/[\u0668\u06F8]/g, '8')
    .replace(/[\u0669\u06F9]/g, '9')
    .trim();
}

